/**
 * Correlation ids (architecture.md §24.1).
 *
 * Ids are drawn exclusively from the injected `Clock`/`Random` ports so that
 * request contexts are reproducible in tests — never `Date.now()` or
 * `Math.random()` (BUILD_PLAN global determinism rule).
 *
 * `request_id` is the only id created here. `job_id` and `generation_id`
 * are owned by the subsystems that create the underlying job/generation
 * (job-engine, index pipeline) — they mint them the same way, via
 * `Random.uuid()`, once those packages exist; minting them here would just
 * move the decision of *when* a job/generation begins out of its owner.
 * `workspace_id`/`repo_id`/`ref_id` are never random — they are the
 * content-derived identities `@untangle-code/domain` already builds
 * (`buildWorkspaceId` et al.) and are attached to a request context by the
 * caller, not generated by observability.
 */
import type { Clock, Random } from "@untangle-code/domain";

export interface RequestContextDeps {
  clock: Clock;
  random: Random;
}

export interface RequestContext {
  /** Random per-operation id (architecture.md §24.1: `request_id`). */
  requestId: string;
  /** Epoch-ms creation time, via `Clock` — never `Date.now()`. */
  createdAtEpochMs: number;
  /** ISO-8601 creation time, via `Clock`. */
  createdAtIso: string;
}

/**
 * Creates a fresh request context. Deterministic given a deterministic
 * `Clock`/`Random` (e.g. in tests): same fakes in, same ids out.
 */
export function createRequestContext(deps: RequestContextDeps): RequestContext {
  return {
    requestId: deps.random.uuid(),
    createdAtEpochMs: deps.clock.nowEpochMs(),
    createdAtIso: deps.clock.nowIso(),
  };
}
