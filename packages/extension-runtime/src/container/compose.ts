/**
 * Rendert die Container-Bereitstellung EINER Extension aus ihrem Manifest.
 *
 * Warum gerendert und nicht die Datei des Nutzers ausgefuehrt: eine mitgebrachte
 * Compose-Datei ist eine zweite Wahrheit neben dem Manifest, und sie ist die
 * schwaechere. Die vorhandene Fassung dieses Projekts nannte etwa
 * `image: <repo>:community` — ein wanderndes Tag. Der Digest im Manifest waere
 * damit reine Dekoration gewesen: gepinnt haette er nichts, weil gezogen wird,
 * was das Tag gerade zeigt (X6). Ebenso wenig kann Untangle einer fremden Datei
 * ansehen, ob sie Loopback bindet, ob sie Labels setzt, ob sie privilegiert
 * startet.
 *
 * Gerendert wird deshalb aus den Feldern, die das Manifest ohnehin deklariert
 * und die Untangle validiert hat. Was hier entsteht, ist genau das, was das
 * Manifest sagt — nicht mehr:
 *
 * - `image@digest`, nie ein Tag (X6);
 * - Portbindungen ausschliesslich an `127.0.0.1` (§8.1);
 * - beide Labels, damit `down` und `logs` spaeter beweisen koennen, dass sie
 *   den eigenen Container meinen und keinen fremden (§8.2);
 * - benannte Volumes mit Praefix `untangle-ext-<id>-`;
 * - kein `privileged`, keine zusaetzlichen Capabilities, kein Host-Netz.
 *
 * Die Ausgabe ist YAML, das ein Compose-fähiges Werkzeug liest. Erzeugt wird
 * sie deterministisch: gleiche Eingabe, bytegleiche Datei.
 */
import type { ExtensionManifestV1 } from "@untangle-code/domain";
import { compareCodepoints } from "@untangle-code/domain";

/** Label, an dem Untangle die eigenen Container erkennt (extensions.md §8.2). */
export const MANAGED_LABEL = "dev.untangle.managed";
/** Label mit der Extension-ID; zusammen mit {@link MANAGED_LABEL} die Besitzprobe. */
export const EXTENSION_LABEL = "dev.untangle.extension";

/** Compose-Projektname einer Extension. */
export function composeProjectName(extensionId: string): string {
  return `untangle-ext-${extensionId}`;
}

/** Name des benannten Volumes einer Extension (extensions.md §11.1). */
export function volumeName(extensionId: string, declaredName: string): string {
  return `untangle-ext-${extensionId}-${declaredName}`;
}

/** Ein Zeichen, das in YAML zitiert werden muss, oder ein fuehrendes Sonderzeichen. */
function yamlString(value: string): string {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

export interface RenderComposeInput {
  manifest: ExtensionManifestV1;
  /**
   * Hostports je Portname. Fehlt ein Eintrag, gilt `hostPortDefault`. Der
   * Aufrufer kann damit einer fremden Instanz ausweichen, ohne das Manifest zu
   * aendern (spec.md §3.2).
   */
  hostPorts?: Readonly<Record<string, number>>;
  /** Absoluter Pfad des Arbeitsbereichs; nur wenn das Manifest ihn einhaengt. */
  workspacePath?: string;
}

/**
 * @throws {Error} wenn das Manifest keinen Container-Block hat. Der Aufrufer
 * prueft das vorher; hier steht es, damit die Funktion nie stillschweigend
 * etwas Halbes rendert.
 */
export function renderComposeFile(input: RenderComposeInput): string {
  const manifest = input.manifest;
  const container = manifest.container;
  if (container === undefined) {
    throw new Error(`extension "${manifest.id}" declares no container block`);
  }
  const id = manifest.id;
  const serviceName = id;

  const lines: string[] = [];
  lines.push(`# Generated by Untangle from extension manifest "${id}".`);
  lines.push("# Do not edit manually: each run regenerates this file from the manifest.");
  lines.push("#");
  lines.push("# The image is pulled by its pinned digest, never a tag (X6).");
  lines.push("# Ports bind only to 127.0.0.1. Both labels establish ownership,");
  lines.push("# allowing `disable --remove-container` to verify that the container belongs");
  lines.push("# to Untangle without touching a foreign container.");
  lines.push(`name: ${composeProjectName(id)}`);
  lines.push("");
  lines.push("services:");
  lines.push(`  ${serviceName}:`);
  lines.push(`    image: ${yamlString(`${container.image}@${container.digest}`)}`);
  lines.push(`    container_name: ${yamlString(`untangle-ext-${id}`)}`);
  lines.push("    labels:");
  lines.push(`      ${MANAGED_LABEL}: "true"`);
  lines.push(`      ${EXTENSION_LABEL}: ${yamlString(id)}`);
  lines.push("    privileged: false");
  lines.push("    cap_drop:");
  lines.push("      - ALL");
  lines.push("    security_opt:");
  lines.push('      - "no-new-privileges:true"');

  const environment = Object.entries(container.environment ?? {}).sort(([left], [right]) =>
    compareCodepoints(left, right),
  );
  if (environment.length > 0) {
    lines.push("    environment:");
    for (const [key, value] of environment) {
      lines.push(`      ${key}: ${yamlString(value)}`);
    }
  }

  if (container.ports.length > 0) {
    lines.push("    ports:");
    for (const port of container.ports) {
      const host = input.hostPorts?.[port.name] ?? port.hostPortDefault;
      lines.push(
        `      - ${yamlString(`127.0.0.1:${String(host)}:${String(port.containerPort)}`)}`,
      );
    }
  }

  const mounts: string[] = [];
  for (const volume of container.volumes) {
    mounts.push(
      `${volumeName(id, volume.name)}:${volume.mountPath}${volume.readOnly ? ":ro" : ""}`,
    );
  }
  if (input.workspacePath !== undefined) {
    const mount = container.workspaceMount;
    mounts.push(`${input.workspacePath}:${mount.mountPath}${mount.readOnly ? ":ro" : ""}`);
  }
  if (mounts.length > 0) {
    lines.push("    volumes:");
    for (const mount of mounts) {
      lines.push(`      - ${yamlString(mount)}`);
    }
  }

  if (container.volumes.length > 0) {
    lines.push("");
    lines.push("volumes:");
    for (const volume of container.volumes) {
      const name = volumeName(id, volume.name);
      lines.push(`  ${name}:`);
      lines.push(`    name: ${yamlString(name)}`);
    }
  }
  return `${lines.join("\n")}\n`;
}
